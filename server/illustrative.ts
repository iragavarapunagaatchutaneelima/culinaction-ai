// ILLUSTRATIVE WORKSPACE GENERATOR
// Creates a separate outlet flagged is_illustrative = 1 with clearly synthetic records so judges can
// try the workflow without real data. Every row has source = 'illustrative'. These are NOT real
// Hyderabad restaurant records, recipes, prices or outcomes, and must never be presented as such.

import { addDays, todayInTz, weekday } from '../shared/dates';
import type { Db } from './db/database';
import { audit } from './services';

function lcg(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 2 ** 32;
  };
}

export async function createIllustrativeOutlet(db: Db, userId: number, now: Date): Promise<number> {
  const today = todayInTz('Asia/Kolkata', now);
  const ts = now.toISOString();
  const rand = lcg(20261010);

  return await db.tx(async () => {
    const outletId = (
      await db.run(
        `INSERT INTO outlets (name, outlet_type, city, locality, service_periods, notes, is_illustrative, created_at, updated_at)
       VALUES (?,?,?,?,?,?,1,?,?)`,
        [
          'Sample Tiffin Centre (Illustrative)',
          'tiffin',
          'Hyderabad',
          'Illustrative locality',
          JSON.stringify(['Breakfast']),
          'ILLUSTRATIVE WORKSPACE: all records are synthetic sample data generated by CulinAction for demonstration. Not a real restaurant.',
          ts,
          ts,
        ],
      )
    ).lastId;
    await db.run('INSERT INTO outlet_members (outlet_id, user_id, role, created_at) VALUES (?,?,?,?)', [
      outletId,
      userId,
      'owner',
      ts,
    ]);

    // name, category, base, [qty, rupees per kg/L/pc, dateType, dateOffset][], countedDaysAgo
    type B = [number, number, string | null, number | null];
    const ingredients: [string, string, 'g' | 'ml' | 'pc', B[], number][] = [
      ['Idli batter', 'Batters', 'g', [[14000, 60, 'use_by', 0]], 0],
      ['Dosa batter', 'Batters', 'g', [[18000, 65, 'use_by', 1]], 0],
      ['Toor dal', 'Pulses', 'g', [[8000, 140, null, null]], 0],
      ['Fresh coconut', 'Produce', 'pc', [[30, 35, null, null]], 0],
      [
        'Milk',
        'Dairy',
        'ml',
        [
          [4000, 62, 'use_by', -1],
          [22000, 62, 'use_by', 2],
        ],
        0,
      ],
      ['Filter coffee powder', 'Beverages', 'g', [[3000, 600, 'best_before', 60]], 0],
      ['Potato', 'Produce', 'g', [[3000, 30, null, null]], 0],
      ['Bombay rava', 'Grains', 'g', [[25000, 50, null, null]], 6],
      ['Sugar', 'Staples', 'g', [[6000, 45, null, null]], 0],
      ['Ghee', 'Dairy', 'g', [[2000, 600, 'best_before', 30]], 0],
      ['Cashew nuts', 'Dry fruits', 'g', [[500, 900, 'best_before', -2]], 0],
    ];
    const ingId: Record<string, number> = {};
    for (const [name, category, base, batches, countedAgo] of ingredients) {
      const counted = new Date(now.getTime() - countedAgo * 86400000).toISOString();
      const id = (
        await db.run(
          'INSERT INTO ingredients (outlet_id, name, category, base_unit, source, last_counted_at, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?)',
          [outletId, name, category, base, 'illustrative', counted, ts, ts],
        )
      ).lastId;
      ingId[name] = id;
      for (const [i, [qty, rupeesPerUnit, dateType, off]] of batches.entries()) {
        const perBase = base === 'pc' ? rupeesPerUnit * 100 : (rupeesPerUnit * 100) / 1000; // paise per g/ml/pc
        const total = Math.round(qty * perBase);
        const received = addDays(today, -(2 + i));
        const bid = (
          await db.run(
            `INSERT INTO inventory_batches (outlet_id, ingredient_id, lot_code, qty_received, qty_remaining, unit_cost_paise, total_cost_paise, received_on, date_type, date_value, source, created_at, updated_at)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)`,
            [
              outletId,
              id,
              `SAMPLE-${id}-${i + 1}`,
              qty,
              qty,
              total / qty,
              total,
              received,
              dateType,
              off === null ? null : addDays(today, off),
              'illustrative',
              ts,
              ts,
            ],
          )
        ).lastId;
        await db.run(
          'INSERT INTO stock_movements (outlet_id, ingredient_id, batch_id, movement_type, qty_delta, reason, user_id, created_at) VALUES (?,?,?,?,?,?,?,?)',
          [outletId, id, bid, 'receipt', qty, 'Illustrative opening stock', userId, ts],
        );
      }
    }

    // name, category, price ₹, verified, recipe lines [ingredient, qty, unit, loss%], base daily demand
    const menu: [
      string,
      string,
      number,
      boolean,
      [string, number, string, number][],
      number,
      string | null,
    ][] = [
      [
        'Idli (2 pc)',
        'Breakfast',
        40,
        true,
        [
          ['Idli batter', 120, 'g', 0],
          ['Toor dal', 25, 'g', 0],
          ['Fresh coconut', 0.1, 'pc', 0],
        ],
        60,
        null,
      ],
      [
        'Masala Dosa',
        'Dosa',
        70,
        true,
        [
          ['Dosa batter', 150, 'g', 0],
          ['Potato', 100, 'g', 10],
          ['Toor dal', 20, 'g', 0],
          ['Fresh coconut', 0.1, 'pc', 0],
        ],
        45,
        null,
      ],
      [
        'Plain Dosa',
        'Dosa',
        50,
        true,
        [
          ['Dosa batter', 150, 'g', 0],
          ['Toor dal', 20, 'g', 0],
          ['Fresh coconut', 0.1, 'pc', 0],
        ],
        25,
        null,
      ],
      [
        'Upma',
        'Breakfast',
        45,
        true,
        [
          ['Bombay rava', 80, 'g', 0],
          ['Ghee', 5, 'g', 0],
        ],
        30,
        'Milk (sample allergen note)',
      ],
      [
        'Filter Coffee',
        'Beverages',
        30,
        true,
        [
          ['Milk', 100, 'ml', 0],
          ['Filter coffee powder', 10, 'g', 0],
          ['Sugar', 10, 'g', 0],
        ],
        120,
        'Milk (sample allergen note)',
      ],
      ['Medu Vada', 'Snacks', 40, false, [], 35, null],
      [
        'Ven Pongal',
        'Breakfast',
        55,
        false,
        [
          ['Toor dal', 30, 'g', 0],
          ['Ghee', 10, 'g', 0],
          ['Cashew nuts', 5, 'g', 0],
        ],
        20,
        null,
      ],
    ];
    const itemId: Record<string, number> = {};
    for (const [name, category, price, verified, lines, , allergens] of menu) {
      const id = (
        await db.run(
          'INSERT INTO menu_items (outlet_id, name, category, price_paise, allergens, allergens_verified, created_at, updated_at) VALUES (?,?,?,?,?,0,?,?)',
          [outletId, name, category, price * 100, allergens, ts, ts],
        )
      ).lastId;
      itemId[name] = id;
      const rid = (
        await db.run(
          'INSERT INTO recipes (menu_item_id, verified, verified_by, verified_at, notes, updated_at) VALUES (?,?,?,?,?,?)',
          [
            id,
            verified ? 1 : 0,
            verified ? userId : null,
            verified ? ts : null,
            'Illustrative recipe quantities — not from a real kitchen.',
            ts,
          ],
        )
      ).lastId;
      for (const [ing, qty, unit, loss] of lines) {
        await db.run(
          'INSERT INTO recipe_ingredients (recipe_id, ingredient_id, qty, unit, loss_pct) VALUES (?,?,?,?,?)',
          [rid, ingId[ing], qty, unit, loss],
        );
      }
    }

    // 28 days of synthetic sales with a weekend uplift
    const salesByDay = new Map<string, number>();
    for (let d = 28; d >= 1; d--) {
      const date = addDays(today, -d);
      const wd = weekday(date);
      const mult = wd === 0 || wd === 6 ? 1.3 : 1;
      for (const [name, , , , , base] of menu) {
        const qty = Math.max(0, Math.round(base * mult * (0.85 + rand() * 0.3)));
        await db.run(
          `INSERT INTO sales_records (outlet_id, sale_date, menu_item_id, service_period, qty, source, created_by, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?)`,
          [outletId, date, itemId[name], 'Breakfast', qty, 'illustrative', userId, ts, ts],
        );
        salesByDay.set(`${date}|${name}`, qty);
      }
    }

    // Synthetic service outcomes for Upma over the last 5 days: consistent over-preparation
    for (let d = 5; d >= 1; d--) {
      const date = addDays(today, -d);
      const sold = salesByDay.get(`${date}|Upma`)!;
      const prepared = 50;
      const discarded = Math.max(0, prepared - sold);
      const oid = (
        await db.run(
          `INSERT INTO service_outcomes (outlet_id, business_date, service_period, menu_item_id, qty_prepared, qty_sold, qty_remaining, qty_discarded, notes, source, created_by, created_at)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?)`,
          [
            outletId,
            date,
            'Breakfast',
            itemId.Upma,
            prepared,
            sold,
            0,
            discarded,
            'Illustrative outcome',
            'illustrative',
            userId,
            ts,
          ],
        )
      ).lastId;
      if (discarded > 0) {
        await db.run(
          `INSERT INTO waste_logs (outlet_id, subject_type, menu_item_id, qty, unit, qty_base, occurred_at, business_date, reason, notes, service_period, cost_paise, cost_basis, outcome_id, source, created_by, created_at)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
          [
            outletId,
            'menu_item',
            itemId.Upma,
            discarded,
            'portions',
            discarded,
            `${date}T05:30:00.000Z`,
            date,
            'over_preparation',
            'Illustrative',
            'Breakfast',
            Math.round(discarded * (80 * 5 + 5 * 60)),
            'recipe_estimate',
            oid,
            'illustrative',
            userId,
            ts,
          ],
        );
      }
    }

    await audit(
      db,
      { outletId, userId, entityType: 'outlet', entityId: outletId, action: 'create_illustrative' },
      now,
    );
    return outletId;
  });
}
